import argparse
import csv
import json
import os
import sys
from collections import defaultdict

import cv2

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, 'src', 'active_perception'))

from active_perception.decision import DecisionParams  # noqa: E402
from active_perception.offline import Detector, evaluate_image  # noqa: E402
from active_perception.view_quality import Thresholds, measure  # noqa: E402

MIN_IOU = 0.3
TESTSET = os.path.join(HERE, 'testset')
OUT = os.path.join(HERE, 'results')

TARGET_FACTOR = {'gaussian_blur': 'sharpness', 'motion_blur': 'sharpness', 'underexpose': 'exposure',
                 'overexpose': 'exposure', 'zoom_out': 'framing', 'zoom_in': 'framing',
                 'shift': 'framing', 'occlusion': 'visibility'}
LEVEL_LABEL = {'gaussian_blur': 'sigma (px)', 'motion_blur': 'kernel length (px)',
               'underexpose': 'gain', 'overexpose': 'gain', 'zoom_out': 'scale',
               'zoom_in': 'magnification', 'shift': 'centre offset (x width)',
               'occlusion': 'fraction of box covered'}


def iou(a, b):
    ix = max(0.0, min(a[2], b[2]) - max(a[0], b[0]))
    iy = max(0.0, min(a[3], b[3]) - max(a[1], b[1]))
    inter = ix * iy
    union = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / union if union > 0 else 0.0


def outcome(result, case, overlap):
    if not result['detected']:
        return 'target_lost'
    if overlap is not None and overlap < MIN_IOU:
        return 'wrong_target'
    if result['passed']:
        return 'passed_local'
    return 'correct' if result['move']['action'] == case['expected_move'] else 'wrong_move'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--model', default=os.path.join(REPO, 'yolov8n.pt'))
    args = ap.parse_args()

    with open(os.path.join(TESTSET, 'manifest.json')) as f:
        manifest = json.load(f)
    th, params = Thresholds(), DecisionParams()
    detectors = {}
    rows = []
    for case in manifest['cases']:
        target = case['target']
        if target not in detectors:
            detectors[target] = Detector(args.model, target)
        img = cv2.imread(os.path.join(TESTSET, case['image']))
        res = evaluate_image(img, detectors[target], th, params)

        conf = res['local']['raw']['confidence'] if res['detected'] else 0.0
        gt = measure(img, case['gt_bbox'], conf, th) if case['gt_bbox'] else None
        overlap = iou(res['bbox'], case['gt_bbox']) if res['detected'] and case['gt_bbox'] else None
        row = {
            'case': case['name'], 'base': case['base'], 'perturbation': case['perturbation'],
            'level': case['level'], 'expected_factor': case['expected_factor'],
            'expected_move': case['expected_move'],
            'detected': res['detected'], 'confidence': round(conf, 3),
            'iou_with_gt': '' if overlap is None else round(overlap, 2),
            'passed_local': res['passed'],
            'failed_factors': ' '.join(res['local']['failed']) if res['detected'] else '',
            'weakest': res.get('weakest', ''),
            'framing_issue': res['local']['framing_issue'] if res['detected'] else '',
            'move': res['move']['action'] if res['move'] else '',
            'move_value': res['move'].get('value', '') if res['move'] else '',
        }
        if gt is not None:
            row.update({f"gt_{k}": round(v, 3) for k, v in gt.raw.items() if isinstance(v, float)})
            row.update({f"gt_score_{k}": round(v, 3) for k, v in gt.scores.items()})
        if case['expected_move']:
            row['outcome'] = outcome(res, case, overlap)
        rows.append(row)
        print(f"{case['name']:40s} det={res['detected']!s:5s} conf={conf:.2f} "
              f"move={row['move'] or '-':9s} {row.get('outcome', '')}")

    os.makedirs(OUT, exist_ok=True)
    fields = []
    for r in rows:
        fields += [k for k in r if k not in fields]
    with open(os.path.join(OUT, 'results.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    write_summary(rows, manifest, th, params, os.path.basename(args.model))
    plot(rows, manifest)
    print(f"Results in {OUT}")


def pct(n, d):
    return f"{n}/{d} ({100.0 * n / d:.0f}%)" if d else "0/0"


def write_summary(rows, manifest, th, params, model):
    L = ["# Evaluation results", "",
         f"Generated by `eval/run_eval.py` (detector `{model}`, default thresholds: "
         f"min_sharpness {th.min_sharpness}, illumination {th.min_illumination}-{th.max_illumination}, "
         f"min_confidence {th.min_confidence}, coverage {th.min_coverage}-{th.max_coverage}, "
         f"max_center_offset {th.max_center_offset}). Local layer only, no VLM calls.", ""]

    L += ["## Clean base views", "", "| base | detected | confidence | passed local check |",
          "|---|---|---|---|"]
    for r in rows:
        if r['perturbation'] == 'clean':
            L.append(f"| {r['base']} | {r['detected']} | {r['confidence']} | {r['passed_local']} |")

    graded = [r for r in rows if r.get('outcome')]
    synth = [r for r in graded if r['perturbation'] != 'natural']
    counts = defaultdict(lambda: defaultdict(int))
    for r in synth:
        counts[r['perturbation']][r['outcome']] += 1
    L += ["", "## Decision outcomes per perturbation (all levels, both bases)", "",
          "| perturbation | expected move | cases | flagged by local check | correct move | "
          "wrong move | passed local check | target lost | wrong object detected |",
          "|---|---|---|---|---|---|---|---|---|"]
    tot = defaultdict(int)
    for pert, spec in manifest['perturbations'].items():
        c = counts[pert]
        n = sum(c.values())
        flagged = c['correct'] + c['wrong_move']
        L.append(f"| {pert} | {spec['expected_move']} | {n} | {flagged} | {pct(c['correct'], flagged)} | "
                 f"{c['wrong_move']} | {c['passed_local']} | {c['target_lost']} | {c['wrong_target']} |")
        for k in ('correct', 'wrong_move', 'passed_local', 'target_lost', 'wrong_target'):
            tot[k] += c[k]
        tot['n'] += n
    flagged = tot['correct'] + tot['wrong_move']
    L.append(f"| **all** | | {tot['n']} | {flagged} | {pct(tot['correct'], flagged)} | "
             f"{tot['wrong_move']} | {tot['passed_local']} | {tot['target_lost']} | {tot['wrong_target']} |")
    L += ["", f"Correct move over all {tot['n']} degraded cases (counting passes and lost targets "
          f"as not correct): {pct(tot['correct'], tot['n'])}.",
          f"A detection counts as the target only if its IoU with the ground-truth box is >= {MIN_IOU}.", "",
          "Weakest factor identified correctly when the local check failed: " +
          pct(sum(1 for r in synth if r['outcome'] in ('correct', 'wrong_move')
                  and r['weakest'] == r['expected_factor']), flagged) + "."]

    L += ["", "## Every case that did not get the expected move", "",
          "| case | outcome | confidence | IoU | failed factors | weakest | framing issue | move chosen |",
          "|---|---|---|---|---|---|---|---|"]
    for r in synth:
        if r['outcome'] in ('wrong_move', 'target_lost', 'wrong_target'):
            L.append(f"| {r['case']} | {r['outcome']} | {r['confidence']} | {r['iou_with_gt']} | "
                     f"{r['failed_factors']} | {r['weakest']} | {r['framing_issue']} | {r['move']} |")

    L += ["", "## Real robot snapshots (hand-labelled)", "",
          "| case | expected move | detected | confidence | failed factors | move chosen | outcome |",
          "|---|---|---|---|---|---|---|"]
    for r in graded:
        if r['perturbation'] == 'natural':
            L.append(f"| {r['case']} | {r['expected_move']} | {r['detected']} | {r['confidence']} | "
                     f"{r['failed_factors']} | {r['move']} | {r['outcome']} |")

    L += ["", "## Metric response (measured on the ground-truth box)", ""]
    for pert in manifest['perturbations']:
        factor = TARGET_FACTOR[pert]
        L += [f"### {pert} ({LEVEL_LABEL[pert]})", "",
              "| base | level | sharpness | illumination | confidence | coverage | centre offset | "
              f"{factor} score |", "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            if r['perturbation'] in ('clean', pert) and 'gt_sharpness' in r:
                L.append(f"| {r['base']} | {r['level'] if r['level'] is not None else 'clean'} | "
                         f"{r['gt_sharpness']:.1f} | {r['gt_illumination']:.1f} | {r['confidence']:.2f} | "
                         f"{r['gt_coverage']:.3f} | {r['gt_center_offset_x']:+.2f} | "
                         f"{r[f'gt_score_{factor}']:.2f} |")
        L.append("")

    with open(os.path.join(OUT, 'summary.md'), 'w') as f:
        f.write("\n".join(L) + "\n")


def plot(rows, manifest):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    colours = {'robot_bottle': '#2a78d6', 'bus_person': '#eb6834'}
    perts = list(manifest['perturbations'])
    fig, axes = plt.subplots(2, 4, figsize=(13, 6), sharey=True)
    for ax, pert in zip(axes.flat, perts):
        factor = TARGET_FACTOR[pert]
        for base, colour in colours.items():
            pts = [(r['level'], r[f'gt_score_{factor}']) for r in rows
                   if r['base'] == base and r['perturbation'] == pert]
            if not pts:
                continue
            xs, ys = zip(*pts)
            ax.plot(xs, ys, color=colour, linewidth=2, marker='o', markersize=5, label=base)
        ax.axhline(0.5, color='#8a8984', linewidth=1, linestyle='--')
        ax.set_title(f"{pert} -> {factor}", fontsize=10, color='#0b0b0b')
        ax.set_xlabel(LEVEL_LABEL[pert], fontsize=9, color='#52514e')
        ax.set_ylim(-0.03, 1.05)
        ax.tick_params(colors='#52514e', labelsize=8)
        for side in ('top', 'right'):
            ax.spines[side].set_visible(False)
        ax.grid(axis='y', color='#e4e3df', linewidth=0.8)
        ax.set_axisbelow(True)
    for ax in axes[:, 0]:
        ax.set_ylabel('factor score (pass >= 0.5)', fontsize=9, color='#52514e')
    handles, labels = axes.flat[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', ncol=2, frameon=False, fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(os.path.join(OUT, 'metric_response.png'), dpi=110, facecolor='white')


if __name__ == '__main__':
    main()
